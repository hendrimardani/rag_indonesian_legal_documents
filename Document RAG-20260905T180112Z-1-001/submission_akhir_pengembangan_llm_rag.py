def generate_with_llama3_template(inputs):
    """
    Memformat prompt menggunakan chat template asli Llama 3
    sesuai format dataset fine-tuning.
    """
    context = inputs["context"]
    question = inputs["question"]

    messages = [
        {"role": "system", "content": system_prompt},
        {"role": "user", "content": "Berapa 10 - 4?"},
        {
            "role": "assistant",
            "content": "<think>\n10 - 4 = 6.\n</think>\n<answer>6</answer>",
        },
        {
            "role": "user",
            "content": f"Konteks:\n{context}\n\nPertanyaan:\n{question}"
        }
    ]

    # Mengubah list dictionary pesan menjadi string berformat token Llama 3 secara otomatis
    # add_generation_prompt=True akan otomatis menambahkan tag <|start_header_id|>assistant<|end_header_id|>\n di akhir
    formatted_prompt = tokenizer.apply_chat_template(
        messages,
        tokenize=False,
        add_generation_prompt=True
    )

    return formatted_prompt

def clean_legal_response(raw_output: str) -> str:
    """
    Membersihkan hasil output LLM dari artefak template chat,
    karakter sampah, dan teks duplikat/berulang di akhir.
    """
    if not raw_output:
        return ""

    # 1. Potong teks seketika menemukan artefak chat Llama 3 atau token sampah
    stop_artifacts = ["CLIIIK", "assistant", "<|start_header_id|>", "<|eot_id|>", "system"]
    for artifact in stop_artifacts:
        if artifact in raw_output:
            raw_output = raw_output.split(artifact)[0]

    # 2. Hapus karakter aneh / mojibake (seperti simbol kotak atau karakter kontrol non-printable)
    raw_output = re.sub(r'[\x00-\x1f\x7f-\x9f]', '', raw_output)

    # 3. Hilangkan paragraf duplikat jika model mengulang teks yang sama persis
    paragraphs = raw_output.strip().split('\n')
    unique_lines = []
    seen = set()

    for line in paragraphs:
        line_clean = line.strip()
        # Jika baris teks sudah pernah dimasukkan dan cukup panjang, anggap sebagai perulangan lalu hentikan
        if line_clean and line_clean in seen and len(line_clean) > 20:
            break
        if line_clean:
            seen.add(line_clean)
        unique_lines.append(line)

    return "\n".join(unique_lines).strip()

